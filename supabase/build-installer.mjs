#!/usr/bin/env node
// Bundle canonical migrations into a fresh installer and a narrow QA upgrade.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = dirname(fileURLToPath(import.meta.url));
const files = readdirSync(join(root, 'migrations')).filter((file) => file.endsWith('.sql')).sort();
function bundle(selected,header){
  const chunks=[...header,'begin;'];
  for (const file of selected) {
    const lines = readFileSync(join(root, 'migrations', file), 'utf8').split(/\r?\n/);
    const wrappers = lines.map((line) => line.trim().toLowerCase()).filter((line) => line === 'begin;' || line === 'commit;');
    if (JSON.stringify(wrappers) !== JSON.stringify(['begin;', 'commit;'])) throw new Error(`Unexpected transaction structure: ${file}`);
    chunks.push('', `-- Source: ${file}`, ...lines.filter((line) => !['begin;', 'commit;'].includes(line.trim().toLowerCase())));
  }
  return `${chunks.join('\n')}\ncommit;\n`;
}
const upgrades=['202611100006_document_formats.sql','202611100007_organisation_type_default.sql'];
for(const file of upgrades)if(!files.includes(file))throw new Error(`Missing QA upgrade source: ${file}`);
const targets=[
  {name:'install-simple-grant.sql',label:'installer',contents:bundle(files,[
    '-- GENERATED by supabase/build-installer.mjs; do not edit directly.',
    '-- Simple Grant shared-project installation. Run ONCE in Supabase SQL Editor.',
    '-- Adds only simple_grant schema, simple-grant-documents bucket and its policies.',
    '-- Does not adopt public tables, update other apps, or alter migration history.',
    '-- Existing schema/name conflicts fail safely. Do not DROP or RESET to bypass them.',
    '-- Capture verify-shared-project.sql output before and after installing.',
  ])},
  {name:'upgrade-qa.sql',label:'QA upgrade',contents:bundle(upgrades,[
    '-- GENERATED by supabase/build-installer.mjs from unchanged 006 and additive 007.',
    '-- Existing Simple Grant installations through 005 or 006: run this COMPLETE file.',
    '-- One transaction, safe to repeat. Do not rerun the fresh installer or reset.',
    '-- Extends only the dedicated private 10 MiB bucket MIME allowlist, preserving extras.',
    '-- Sets organisation type default to unknown for FUTURE records only.',
    '-- All existing organisation values, documents, policies and shared Auth stay intact.',
    '-- Does not read/write another app or alter shared migration history.',
  ])},
];
let stale=false;
for(const target of targets){
  const path=join(root,target.name);
  if(process.argv.includes('--check')){
    let actual;try{actual=readFileSync(path,'utf8')}catch{actual=null}
    if(actual!==target.contents){process.stderr.write(`${target.name} is stale. Run node supabase/build-installer.mjs.\n`);stale=true;}
    else process.stdout.write(`PASS: ${target.label} exactly matches canonical migrations.\n`);
  }else writeFileSync(path,target.contents);
}
if(stale)process.exitCode=1;
